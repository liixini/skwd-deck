const FLOAT_POSITIONS: &[&str] = &[
    filter_bar::ARRANGE_POSITION_ENABLED,
    filter_bar::ARRANGE_POSITION_X,
    filter_bar::ARRANGE_POSITION_Y,
    filter_bar::SWATCH_POSITION_ENABLED,
    filter_bar::SWATCH_POSITION_X,
    filter_bar::SWATCH_POSITION_Y,
];
const FLOAT_SHOWS: &[&str] = &[filter_bar::SHOW_ARRANGE, filter_bar::SHOW_SWATCH];

fn corners() -> impl Iterator<Item = &'static str> {
    crate::corners::ALL
        .iter()
        .flat_map(|keys| [keys.style, keys.same, keys.all].into_iter().chain(keys.values))
}

pub(super) fn retire(values: &mut BTreeMap<String, Option<Value>>) {
    let Some(old) = values.remove(general::LEGACY_FILTER_BAR_ALWAYS_VISIBLE) else { return };
    let pinned = old.as_ref().and_then(Value::as_bool).unwrap_or(true);
    let mode = if pinned { FilterBarVisibility::Always } else { FilterBarVisibility::Hover };
    values
        .entry(general::FILTER_BAR_VISIBILITY.to_owned())
        .or_insert_with(|| Some(Value::String(mode.key().to_owned())));
}

pub(super) fn paths() -> impl Iterator<Item = &'static str> {
    PATHS.iter().copied().chain(corners())
}

pub fn owns(path: &str) -> bool {
    paths().any(|owned| owned == path)
}

pub fn optional(path: &str) -> bool {
    optional_paths().any(|optional| optional == path)
}

pub fn optional_paths() -> impl Iterator<Item = &'static str> {
    FLOAT_POSITIONS.iter().chain(FLOAT_SHOWS).copied().chain(corners())
}

pub(super) fn reset_paths() -> impl Iterator<Item = &'static str> {
    FLOAT_POSITIONS.iter().copied().chain(corners())
}
